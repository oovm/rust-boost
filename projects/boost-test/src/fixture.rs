//! Explicit fixture setup and teardown.
//!
//! A fixture is a typed value owned by the runner for one execution. Setup runs before the body and
//! teardown runs after it, including after a body panic. The runner never shares a fixture through
//! global mutable state, so every case owns its own value and its own cleanup order.

use core::fmt::{self, Display, Formatter};

use crate::{
    context::TestContext,
    descriptor::SourceLocation,
    result::{IntoTestFailure, TestFailure},
};

/// Identity of a fixture declaration.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub struct FixtureDescriptor {
    name: String,
    source: SourceLocation,
}

impl FixtureDescriptor {
    /// Creates a descriptor from the declared name and the macro invocation location.
    pub fn new(name: impl Into<String>, source: SourceLocation) -> Self {
        Self { name: name.into(), source }
    }

    /// Returns the declared fixture name.
    pub fn name(&self) -> &str {
        &self.name
    }

    /// Returns the source location captured by the macro.
    pub fn source(&self) -> &SourceLocation {
        &self.source
    }
}

impl Display for FixtureDescriptor {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> fmt::Result {
        formatter.write_str(&self.name)
    }
}

/// A typed fixture with explicit setup and teardown.
///
/// Setup receives the context, so a fixture may request a skip before the body runs. Teardown
/// consumes the value, runs even when the body failed or panicked, and cannot replace the body's
/// original failure: the runner records teardown evidence as additional failures.
///
/// The implementation is normally generated by `#[boost_test::fixture]` on a setup function. The
/// generated marker type lives in the type namespace under the setup function's name, while the
/// setup function itself stays callable.
pub trait Fixture {
    /// The value owned by the runner and borrowed by the body.
    type Value;

    /// Returns the identity of the fixture declaration.
    fn descriptor() -> FixtureDescriptor;

    /// Creates the value.
    fn setup(context: &mut TestContext) -> Result<Self::Value, TestFailure>;

    /// Releases the value.
    fn teardown(value: Self::Value) -> Result<(), TestFailure>;
}

/// Normalizes the result of a teardown function.
///
/// A teardown may return `()` or `Result<(), E>`. The generated fixture implementation passes the
/// call result through this trait, so both forms keep their error evidence instead of requiring a
/// separate macro attribute for each shape.
pub trait IntoTeardown {
    /// Converts the teardown result into structured failure evidence.
    fn into_teardown(self) -> Result<(), TestFailure>;
}

impl IntoTeardown for () {
    fn into_teardown(self) -> Result<(), TestFailure> {
        Ok(())
    }
}

impl<E> IntoTeardown for Result<(), E>
where
    E: IntoTestFailure,
{
    fn into_teardown(self) -> Result<(), TestFailure> {
        self.map_err(IntoTestFailure::into_test_failure)
    }
}
